# ─── Helper ──────────────────────────────────────────────────────────────
def tbl(cols):
    """Build a vixor-table HTML string. cols = [(header, rows), ...]"""
    ths = "".join(f"<th>{h}</th>" for h, _ in cols)
    rows_html = ""
    max_len = max(len(r) for _, r in cols)
    for i in range(max_len):
        cells = ""
        for _, r in cols:
            val = r[i] if i < len(r) else ""
            cells += f"<td>{val}</td>"
        rows_html += f"<tr>{cells}</tr>"
    return f'<table class="vixor-table"><thead><tr>{ths}</tr></thead><tbody>{rows_html}</tbody></table>'


def adr_card(status, date, decision):
    """ADR metadata card."""
    return f"""
<div class="callout">
    <div class="callout-title">ملخص القرار</div>
    <div class="callout-body">
        <strong>الحالة:</strong> {status} &nbsp;|&nbsp; <strong>التاريخ:</strong> {date} &nbsp;|&nbsp; <strong>القرار:</strong> {decision}
    </div>
</div>"""


def pro_con(pros, cons):
    """Pros and cons card grid."""
    cards = ""
    for title, items, color in pros:
        items_html = "".join(f"<li>{item}</li>" for item in items)
        cards += f"""
<div class="info-card">
    <div class="info-card-title">{title}</div>
    <div class="info-card-body"><ul class="vixor-list" style="padding-right:14px;">{items_html}</ul></div>
</div>"""
    for title, items, color in cons:
        items_html = "".join(f"<li>{item}</li>" for item in items)
        cards += f"""
<div class="info-card">
    <div class="info-card-title">{title}</div>
    <div class="info-card-body"><ul class="vixor-list" style="padding-right:14px;">{items_html}</ul></div>
</div>"""
    return f'<div class="card-grid">{cards}</div>'


