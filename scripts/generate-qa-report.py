class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))

def add_heading(text, style, level=0):
    key = f"h_{hashlib.md5(text.encode()).hexdigest()[:8]}"
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def on_cover_page(canvas_obj, doc):
    canvas_obj.saveState()
    # Full dark background
    canvas_obj.setFillColor(PAGE_BG)
    canvas_obj.rect(0, 0, PAGE_W, PAGE_H, fill=1, stroke=0)
    # Decorative top band
    canvas_obj.setFillColor(COVER_BLOCK)
    canvas_obj.rect(0, PAGE_H - 8*mm, PAGE_W, 8*mm, fill=1, stroke=0)
    # Accent line
    canvas_obj.setStrokeColor(ACCENT)
    canvas_obj.setLineWidth(2)
    canvas_obj.line(MARGIN, PAGE_H - 14*mm, PAGE_W - MARGIN, PAGE_H - 14*mm)
    # Bottom corner mark
    canvas_obj.setFillColor(ACCENT)
    canvas_obj.rect(MARGIN, MARGIN, 4*mm, 4*mm, fill=1, stroke=0)
    canvas_obj.setFillColor(TEXT_MUTED)
    canvas_obj.setFont(FONT_REG, 8)
    canvas_obj.drawString(MARGIN + 7*mm, MARGIN + 1.5*mm, "VIXOR MASTER V2  |  Confidential Engineering Report")
    canvas_obj.restoreState()

def on_content_page(canvas_obj, doc):
    canvas_obj.saveState()
    # Header line
    canvas_obj.setStrokeColor(BORDER)
    canvas_obj.setLineWidth(0.5)
    canvas_obj.line(MARGIN, PAGE_H - 12*mm, PAGE_W - MARGIN, PAGE_H - 12*mm)
    canvas_obj.setFont(FONT_REG, 8)
    canvas_obj.setFillColor(TEXT_MUTED_DARK)
    canvas_obj.drawString(MARGIN, PAGE_H - 9*mm, "VIXOR MASTER V2 — QA & Monitoring Report")
    canvas_obj.drawRightString(PAGE_W - MARGIN, PAGE_H - 9*mm, datetime.now().strftime("%Y-%m-%d"))
    # Footer
    canvas_obj.setStrokeColor(BORDER)
    canvas_obj.line(MARGIN, 14*mm, PAGE_W - MARGIN, 14*mm)
    canvas_obj.setFont(FONT_REG, 8)
    canvas_obj.setFillColor(TEXT_MUTED_DARK)
    canvas_obj.drawString(MARGIN, 9*mm, "Generated by Vixor QA Engine")
    canvas_obj.drawRightString(PAGE_W - MARGIN, 9*mm, f"Page {doc.page}")
    canvas_obj.restoreState()

